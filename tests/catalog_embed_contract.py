#!/usr/bin/env python3
"""Verify that CMake embeds the exact manifest bytes without oversized literals."""
from __future__ import annotations

import re
import sys
from pathlib import Path


def fail(message: str) -> None:
    raise SystemExit(f"catalog embed contract failed: {message}")


def main() -> None:
    if len(sys.argv) != 3:
        fail("usage: catalog_embed_contract.py MANIFEST HEADER")
    manifest_path = Path(sys.argv[1])
    header_path = Path(sys.argv[2])
    expected = manifest_path.read_bytes() + b"\x00"
    header = header_path.read_text(encoding="utf-8")
    start_marker = "embedded_manifest_json[] = {"
    start = header.find(start_marker)
    if start < 0:
        fail("generated header has no embedded byte array")
    body_start = header.find("{", start) + 1
    body_end = header.find("};", body_start)
    if body_end < 0:
        fail("generated byte array is not terminated")
    body = header[body_start:body_end]
    encoded = bytes(int(value, 16) for value in re.findall(r"0x([0-9A-Fa-f]{2})", body))
    if encoded != expected:
        fail("embedded bytes do not exactly match manifest UTF-8 bytes plus NUL")
    for line_number, line in enumerate(body.splitlines(), 1):
        byte_count = len(re.findall(r"0x[0-9A-Fa-f]{2}", line))
        if byte_count > 16:
            fail(f"generated line {line_number} contains more than 16 byte literals")
    print(f"catalog embed contract passed: {len(expected) - 1} manifest bytes")


if __name__ == "__main__":
    main()
